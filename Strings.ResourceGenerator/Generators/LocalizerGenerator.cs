using System;
using System.Collections.Generic;
using System.Linq;
using Strings.ResourceGenerator.Exceptions;
using Strings.ResourceGenerator.Generators.Emit;
using Strings.ResourceGenerator.Generators.Headers;
using Strings.ResourceGenerator.Generators.Interfaces;
using Strings.ResourceGenerator.Models;
using Strings.ResourceGenerator.Resources;

namespace Strings.ResourceGenerator.Generators;

internal class LocalizerGenerator
{
    private readonly Dictionary<string, IGenerator> generators = [];

    internal LocalizerGenerator(StringConfiguration config, string clazz)
    {
        this.Config = config;
        Clazz = clazz;
    }

    private string AccessModifier => Config.GeneratePublic ? "public" : "internal";
    private string Prefix => Config.Prefix;

    /// <summary>
    /// Add a generator for a locale
    /// </summary>
    /// <param name="generator"></param>
    public void AddStringLocalizer(IGenerator generator, string locale)
    {
        if (string.IsNullOrWhiteSpace(locale))
        {
            locale = Constants.Neutral;
        }
        generators[locale] = generator;
    }

    public bool IsMultipleLanguages => generators.Count > 1;

    public string Clazz { get; }
    private readonly List<string> errors = [];
    internal StringConfiguration Config { get; private set; }

    /// <summary>
    /// Generate resource classes for the localizer
    /// </summary>
    /// <returns>The text for the string localizer</returns>
    /// <exception cref="StringGeneratorException"></exception>
    public string Generate()
    {
        var w = new CodeWriter();

        w.Line("// <auto-generated/>");
        w.Line();
        w.Line("using System;");
        w.Line("using System.Collections.Generic;");
        w.Line("using System.Globalization;");
        w.Line();
        w.Line($"namespace {Config.NameSpace}");
        using (w.OpenBlock())
        {
            WriteAssemblyCommentHeader(w);

            w.EmitLine(Indent.Spaces(1).ExcludeAttributeIndented(Config.ExcludeFromCodeCoverage, Config.ExcludeFromCodeCoverageMessage));
            w.Line($"{AccessModifier} static class {Prefix}{Clazz}");
            using (w.OpenBlock())
            {
                if (IsMultipleLanguages)
                {
                    WriteMultiLanguageInfrastructure(w);
                }

                // Loop through the resources and generate interface and locale classes
                w.Line();
                if (IsMultipleLanguages)
                {
                    w.Line("#region String accessors");
                    foreach (var res in generators[Constants.Neutral].Data.Resources)
                    {
                        var decl = res.StaticProperty;

                        IEnumerable<string> Values()
                        {
                            foreach (var generator in generators.Values)
                            {
                                var subRes = generator.Data.Resources.FirstOrDefault(x => x.Key == res.Key);
                                yield return $"{generator.Data.Locale}: {subRes?.CleanValueNonImplementation ?? "Missing documentation"}";
                            }
                        }

                        foreach (var value in ImplementationGenerator.DocumentationLines(decl, res.Context, Values().ToArray()))
                        {
                            w.EmitLine(value);
                        }

                        w.EmitLine(decl);
                    }

                    w.Line("#endregion");
                }
                else
                {
                    w.EmitLine(generators[generators.Keys.First()].GenerateStaticAccessors());
                }

                w.Line();
                w.Line("/// <summary>");
                w.Line($"/// {LocalStrings.Unescape(LocalStrings.FormatDoc)}");
                w.Line("/// </summary>");
                w.Line($"{AccessModifier} static string Format(string name, params object[] args)");
                using (w.OpenBlock())
                {
                    w.Line("return args == null || args.Length == 0 ? name : string.Format(name, args);");
                }

                w.Line();
                w.Line("/// <summary>");
                w.Line($"/// {LocalStrings.Unescape(LocalStrings.UnescapeDoc)}");
                w.Line("/// </summary>");
                w.Line("public static string Unescape(string value)");
                using (w.OpenBlock())
                {
                    w.Line("return value.Replace(\"\\\\\", \"\");");
                }

                w.Line();

                if (IsMultipleLanguages)
                {
                    w.Line("/// <summary>");
                    w.Line($"/// {LocalStrings.Unescape(LocalStrings.GetStringDoc)}");
                    w.Line("/// </summary>");
                    w.Line("public static string GetString(string name, params object[] args) => Current.GetString(name, args);");
                    w.Line();
                    w.Line("/// <summary>");
                    w.Line($"/// {LocalStrings.Unescape(LocalStrings.GetStringOrEmptyDoc)}");
                    w.Line("/// ");
                    w.Line("/// </summary>");
                    w.Line("public static string GetStringOrEmpty(string name, params object[] args) => Current.GetStringOrEmpty(name, args);");
                    w.Line();

                    ValidateLocaleKeyCoverage();

                    w.EmitLine(generators[Constants.Neutral].GenerateInterface());
                    w.EmitLine(generators[Constants.Neutral].GenerateBaseType());
                    foreach (var impl in generators.Values.OrderBy(x => x.Data.Locale))
                    {
                        w.EmitLine(impl.GenerateClass());
                    }
                }
            }
        }

        if (errors.Count > 0)
        {
            throw new StringGeneratorException($"Errors during string generation", errors);
        }

        return w.ToString();
    }

    private void WriteAssemblyCommentHeader(CodeWriter w)
    {
        const string headerCommentPrefix = "// ";
        var v = typeof(LocalizerGenerator).Assembly.GetName().Version;
        w.Line($"{headerCommentPrefix} Strings.ResourceGenerator v{v} by Status ehf - Generated {DateTime.UtcNow:yyyy-MM-dd HH:mm:ss} (UTC)");
        w.Line($"{headerCommentPrefix} Generated from: {string.Join(", ", generators.Select(x => x.Value.Data.SourceFile))}");
        ResourceStatisticsCommentsEmitter.Write(w, generators.First().Value);

        w.Line("/// <summary>");
        w.Line($"/// Generated string accessor class for {Prefix}{Clazz}");
        w.Line($"/// Configuration [{Config.ConfigurationSource}]");
        w.Line($"///     Namespace              : {Config.NameSpace}");
        w.Line($"///     Public                 : {Config.GeneratePublic}");
        w.Line($"///     Prefix                 : {Config.Prefix}");
        w.Line($"///     Const                  : {Config.PreferConstOverStatic}");
        w.Line($"///     ExcludeCoverage        : {Config.ExcludeFromCodeCoverage}");
        w.Line($"///     ExcludeCoverageMessage : {Config.ExcludeFromCodeCoverageMessage}");
        w.Line("/// </summary>");
    }

    private void WriteMultiLanguageInfrastructure(CodeWriter w)
    {
        if (generators.Count > 1)
        {
            w.Line("// Lazy initializers for each locale");
            foreach (var generator in generators.Values)
            {
                w.Line($"private static readonly Lazy<IGeneratedLocalizerFor{Prefix}{Clazz}> _{generator.Data.Locale.ToLower()} = new Lazy<IGeneratedLocalizerFor{Prefix}{Clazz}>(() => InitializeLocalizerFor(\"{generator.Data.Locale}\"));");
            }
        }

        w.Line();
        w.Line($"private static IGeneratedLocalizerFor{Prefix}{Clazz} InitializeLocalizerFor(string locale)");
        var index = 0;
        using (w.OpenBlock())
        {
            foreach (var generator in generators.Values.Where(x => !x.Data.IsNeutralLanguage).Select(x => x))
            {
                w.Line($"{(index == 0 ? "" : "else ")}if (locale == \"{generator.Data.Locale}\")");
                using (w.OpenBlock())
                {
                    w.Line($"return new {generator.GeneratedClassName(generator.Data.Locale)}();");
                }

                index++;
            }

            if (generators.Count > 1)
            {
                w.Line("else");
                using (w.OpenBlock())
                {
                    w.Line($"return new GeneratedLocalizerFor{Prefix}{Clazz}Neutral();");
                }
            }
            else
            {
                w.Line($"return new GeneratedLocalizerFor{Prefix}{Clazz}Neutral();");
            }
        }

        index = 0;
        w.Line();
        w.Line($"private static IGeneratedLocalizerFor{Prefix}{Clazz} Current");
        using (w.OpenBlock())
        {
            w.Line("get");
            using (w.OpenBlock())
            {
                foreach (var generator in generators.Values.Where(x => !x.Data.IsNeutralLanguage).Select(x => x))
                {
                    w.Line($"{(index == 0 ? "" : "else ")}if (CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToUpper() == \"{generator.Data.Locale}\")");
                    using (w.OpenBlock())
                    {
                        w.Line($"return _{generator.Data.Locale.ToLower()}.Value;");
                    }

                    index++;
                }

                if (generators.Count > 1)
                {
                    w.Line("else");
                    using (w.OpenBlock())
                    {
                        w.Line("return _neutral.Value;");
                    }
                }
                else
                {
                    w.Line("return _neutral.Value;");
                }
            }
        }

        foreach (var generator in generators.Values)
        {
            w.Line();
            var name = generator.Data.IsNeutralLanguage ? "Neutral" : generator.Data.Locale.ToUpper();
            var modifier = generator.Data.Config.GeneratePublic ? "public" : "internal";
            w.Line("/// <summary>");
            w.Line($"/// Accessor for the '{generator.Data.Locale.ToLower()}' locale");
            w.Line("/// </summary>");
            w.Line($"{modifier} static IGeneratedLocalizerFor{Prefix}{Clazz} {name} => _{generator.Data.Locale.ToLower()}.Value;");
        }
    }

    private void ValidateLocaleKeyCoverage()
    {
        var countsByKey = generators.Values
            .SelectMany(g => g.Data.Resources)
            .GroupBy(r => r.Key)
            .ToDictionary(g => g.Key, g => g.Count());

        var mismatchedKeys = countsByKey
            .Where(p => p.Value != generators.Count)
            .Select(p => p.Key)
            .ToList();

        if (mismatchedKeys.Count > 0)
        {
            errors.Add($"{generators.First().Value.Data.SourceFile}: Invalid resource values for the following resource: " +
                string.Join(", ", mismatchedKeys));
        }
    }
}
